using System;

namespace XForms
{
    /// <summary>
    /// Where a view sits horizontally in the space its parent gives it.
    /// </summary>
    public enum HorizontalAlignment
    {
        Left = 0,
        Center = 1,
        Right = 2,
        Stretch = 3,
    }

    /// <summary>
    /// Where a view sits vertically in the space its parent gives it.
    /// </summary>
    public enum VerticalAlignment
    {
        Top = 0,
        Center = 1,
        Bottom = 2,
        Stretch = 3,
    }
}
